"""## Decision Tree Modeling
We will clean the dataset by converting features to numerical types, handling missing values, and then train a Decision Tree model to predict `Calories`.
"""

import numpy as np
from sklearn.tree import DecisionTreeRegressor
from sklearn.metrics import mean_squared_error, r2_score
import matplotlib.pyplot as plt
from sklearn import tree

# Prepare copy of datasets
train_clean = train_df.copy()
test_clean = test_df.copy()

# Identify feature columns (ignoring index/name column and target)
exclude_cols = [train_clean.columns[0], 'Calories']
feature_cols = [col for col in train_clean.columns if col not in exclude_cols]

# Clean and convert data (handling standard '-' placeholders)
for col in [ 'Calories'] + feature_cols:
    train_clean[col] = pd.to_numeric(train_clean[col].astype(str).str.replace('-', 'nan'), errors='coerce')
    test_clean[col] = pd.to_numeric(test_clean[col].astype(str).str.replace('-', 'nan'), errors='coerce')

# Fill missing values with median values from the training set
for col in [ 'Calories'] + feature_cols:
    median_val = train_clean[col].median()
    if pd.isna(median_val):
        median_val = 0
    train_clean[col] = train_clean[col].fillna(median_val)
    test_clean[col] = test_clean[col].fillna(median_val)

# Separate features and target
X_train = train_clean[feature_cols]
y_train = train_clean['Calories']
X_test = test_clean[feature_cols]
y_test = test_clean['Calories']

# Initialize and train Decision Tree Regressor
dt_model = DecisionTreeRegressor(max_depth=4, random_state=42)
dt_model.fit(X_train, y_train)

# Evaluate predictions
train_preds = dt_model.predict(X_train)
test_preds = dt_model.predict(X_test)

print("Model Evaluation Summary:")
print(f"Train MSE: {mean_squared_error(y_train, train_preds):.2f} | Train R^2: {r2_score(y_train, train_preds):.2f}")
print(f"Test MSE:  {mean_squared_error(y_test, test_preds):.2f} | Test R^2:  {r2_score(y_test, test_preds):.2f}")

"""### Visualizing the Decision Tree Structure"""

plt.figure(figsize=(16, 8))
tree.plot_tree(dt_model, feature_names=feature_cols, filled=True, rounded=True, fontsize=10)
plt.title("Decision Tree Structure for Predicting Calories")
plt.show()

